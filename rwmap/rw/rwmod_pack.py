""".rwmod 打包（ZIP + mod-info.txt + tmx + 缩略图）。"""
from __future__ import annotations

import zipfile
from pathlib import Path

from ..utils.paths import as_path


def pack_rwmod(tmx_path, out_path, png_path=None, title="", description="") -> dict:
    tmx = as_path(tmx_path)
    out = as_path(out_path)
    png = as_path(png_path) if png_path else tmx.with_name(tmx.stem + "_map.png")
    out.parent.mkdir(parents=True, exist_ok=True)
    info = (
        "[mod]\n"
        f"title: {title or tmx.stem}\n"
        f"description: {description or 'Generated by rwmap'}\n"
        "tags: maps\n"
        f"thumbnail: {png.name}\n"
    )
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.write(tmx, tmx.name)
        if png.is_file():
            zf.write(png, png.name)
        zf.writestr("mod-info.txt", info)
    return {"ok": True, "path": str(out), "entries": len([tmx.name, png.name, "mod-info.txt"])}
